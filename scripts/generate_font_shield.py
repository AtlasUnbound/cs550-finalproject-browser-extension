"""
PrintShield font shield generator.

Reads scripts/font-lists.json and writes:
  * content/fonts/font-shield-{win,mac,linux}.css
      One @font-face rule per blocked font. Each rule defines the family with a
      standard OS font that only covers U+10FFFF (a code point that never appears
      in text). Because the family is now defined by a stylesheet, the locally
      installed font of the same name is shadowed, and since no real character is
      covered the browser falls back to the next font in the list -- exactly what
      happens on a computer that never installed that font.
      (A rule whose source fails to load does NOT work: Chrome then falls back to
      the installed font, so the source must be a font that exists on the OS.)
      Web fonts that a site loads itself still win, because they cover real text.
      Fonts in "common_extras" (the fonts most users of the OS also have, such as
      the Microsoft Office pack on Windows) get an "emulate" rule instead:
      local("<font>") first, so people who have it see the real font, then a
      standard OS font, so people who don't have it still appear to. Everyone on
      the OS then shows the same, most common font list.
  * the FONT_ALLOWLIST block inside content/protector-main.js (used by the
    document.fonts.check() mitigation).

Usage:  python scripts/generate_font_shield.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
LISTS = json.loads((ROOT / "scripts" / "font-lists.json").read_text(encoding="utf-8"))
OUT_DIR = ROOT / "content" / "fonts"
PROTECTOR = ROOT / "content" / "protector-main.js"

HEADER = """/* GENERATED by scripts/generate_font_shield.py -- do not edit by hand.
 * PrintShield font shield ({os}): makes every {label} user show the same, most common
 * font list -- {count} uncommon fonts are hidden and the common profile is emulated.
 */
"""
LABELS = {"win": "Windows", "mac": "macOS", "linux": "Linux"}
# Fonts that exist on (nearly) every install of each OS, tried in order.
LOCAL_SOURCES = {
    "win": 'local("Arial"), local("Segoe UI"), local("Tahoma")',
    "mac": 'local("Helvetica"), local("Arial"), local("Geneva")',
    "linux": 'local("DejaVu Sans"), local("Liberation Sans"), local("Noto Sans"), local("FreeSans"), local("Arial")',
}


def css_string(name: str) -> str:
    return '"' + name.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    for os_key, label in LABELS.items():
        defaults = {f.lower() for f in LISTS["allow"][os_key]}
        extras = [f for f in LISTS["common_extras"][os_key] if f.lower() not in defaults]
        profile = defaults | {f.lower() for f in extras}
        blocked = [f for f in LISTS["block"] if f.lower() not in profile]
        # "Emulate" faces use U+0-10FFFE and "hide" faces U+10FFFF, so protector-main.js
        # can recognise (and hide) both from document.fonts.
        emulate = [
            f"@font-face {{ font-family: {css_string(f)}; src: local({css_string(f)}), {LOCAL_SOURCES[os_key]}; unicode-range: U+0-10FFFE; }}"
            for f in extras
        ]
        hide = [
            f"@font-face {{ font-family: {css_string(f)}; src: {LOCAL_SOURCES[os_key]}; unicode-range: U+10FFFF; }}"
            for f in blocked
        ]
        text = HEADER.format(os=os_key, count=len(blocked), label=label) + "\n".join(emulate + hide) + "\n"
        (OUT_DIR / f"font-shield-{os_key}.css").write_text(text, encoding="utf-8")
        print(f"font-shield-{os_key}.css: {len(blocked)} fonts hidden, {len(extras)} common fonts emulated")

    profiles = {k: sorted(set(LISTS["allow"][k]) | set(LISTS["common_extras"][k]), key=str.lower) for k in LABELS}
    allow_js = json.dumps(profiles, indent=2, ensure_ascii=False)
    allow_js = "\n".join("  " + line if i else line for i, line in enumerate(allow_js.splitlines()))
    block = f"// @@FONT_ALLOWLIST_BEGIN\n  const FONT_ALLOWLIST = {allow_js};\n  // @@FONT_ALLOWLIST_END"
    src = PROTECTOR.read_text(encoding="utf-8")
    new_src, n = re.subn(r"// @@FONT_ALLOWLIST_BEGIN.*?// @@FONT_ALLOWLIST_END", lambda _m: block, src, flags=re.S)
    if n != 1:
        raise SystemExit("FONT_ALLOWLIST markers not found in protector-main.js")
    PROTECTOR.write_text(new_src, encoding="utf-8")
    print("protector-main.js: FONT_ALLOWLIST updated")


if __name__ == "__main__":
    main()
